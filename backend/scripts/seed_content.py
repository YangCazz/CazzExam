def main():
    db = SessionLocal()
    code2id = {k.code: k.id for k in db.query(KnowledgePoint).all()}
    added_kp = 0
    for parent_code, code, name, desc, subject in KNOWLEDGE:
        if code in code2id:
            continue
        parent_id = code2id.get(parent_code)
        kp = KnowledgePoint(parent_id=parent_id, code=code, name=name, description=desc, subject=subject)
        db.add(kp)
        db.flush()
        code2id[code] = kp.id
        added_kp += 1
    db.commit()
    print("knowledge points added:", added_kp, "total:", len(code2id))

    added_rel = 0
    for fc, tc, rt in RELATIONS:
        f, t = code2id.get(fc), code2id.get(tc)
        if not f or not t:
            print("skip relation", fc, tc)
            continue
        dup = db.query(KnowledgeRelation).filter_by(from_id=f, to_id=t, relation_type=rt).first()
        if dup:
            continue
        db.add(KnowledgeRelation(from_id=f, to_id=t, relation_type=rt))
        added_rel += 1
    db.commit()
    print("relations added:", added_rel)

    existing = {q.stem for q in db.query(Question).all()}
    added_q = 0
    for qtype, subject, stem, opts, answer, analysis, diff, kp_codes, *rest in QUESTIONS:
        items = rest[0] if rest else []
        if stem in existing:
            continue
        q = Question(qtype=qtype, subject=subject, stem=stem,
                     options_json=__import__("json").dumps(opts, ensure_ascii=False),
                     answer_json=__import__("json").dumps(answer, ensure_ascii=False),
                     analysis=analysis, difficulty=diff, source_type="self", status="active")
        db.add(q)
        db.flush()
        for kc in kp_codes:
            kid = code2id.get(kc)
            if kid:
                db.add(QuestionKnowledge(question_id=q.id, knowledge_id=kid))
        for seq, (ist, ia, sc) in enumerate(items, 1):
            db.add(QuestionItem(question_id=q.id, seq=seq, stem=ist, answer=ia, score=sc))
        added_q += 1
        existing.add(stem)
    db.commit()
    print("questions added:", added_q)
    db.close()

if __name__ == "__main__":
    main()
